// Captured once from verified 47f0fc18, not generated by this test. Preserve the
// evidence when introducing another engine; do not make it follow new behavior.
const backupText = readFileSync(new URL("./fixtures/v2/corrections-and-settlement.backup.json", import.meta.url), "utf8");
const stateText = readFileSync(new URL("./fixtures/v2/corrections-and-settlement.state.json", import.meta.url), "utf8");
const provenanceText = readFileSync(new URL("./fixtures/v2/provenance.json", import.meta.url), "utf8");
type CapturedRow = Record<string, unknown> & {
  revision: number; command_key: string; command_type: string; occurred_at_ms: string;
  command_json: unknown; input_hash: string; result_json: unknown; result_hash: string;
  state_hash: string; previous_event_hash: string; event_hash: string;
};
type Correction = {
  label: string; requestId: string; proposalId: string; action: string; priorCheckpoint: V2Checkpoint;
  revision: number; commandKey: string; eventHash: string; receipt: V2AcceptanceReceipt;
};
const captured = JSON.parse(backupText) as { commands: CapturedRow[]; continuation: unknown };
const capturedState: unknown = JSON.parse(stateText);
const provenance = JSON.parse(provenanceText) as {
  sourceCommit: string; sourceTree: string; checkoutAtCapture: string; engineVersion: string; backupFormatVersion: number;
  sourceSha256: Record<string, string>; prefixCheckpoint: V2Checkpoint; checkpoint: V2Checkpoint; backupChecksum: string;
  facts: { commands: number; enrollments: number; acceptanceReceipts: number; corrections: Correction[] };
};
// The immutable provenance preserves all 33 capture-source hashes. Only financial
// interpretation is byte-frozen here; transport hardening is checked by replay,
// restore and reopen against the original, independently captured history below.
const FROZEN_FINANCIAL_SOURCES = [
  "src/lib/alpha-wallet/amounts.ts", "src/lib/alpha-wallet/commands.ts", "src/lib/alpha-wallet/ledger.ts",
  "src/lib/alpha-wallet/sandbox.ts", "src/lib/alpha-wallet/types.ts", "src/lib/alpha-wallet/accepted-terms.ts",
  "src/lib/alpha-wallet/v2-commands.ts", "src/lib/alpha-wallet/v2-engine.ts", "src/lib/alpha-wallet/v2-kernel.ts",
  "src/lib/trade-amount-lock.ts", "src/lib/trade-cancellation.ts", "src/lib/usdt-demand-policy.ts",
  "src/lib/marketplace-payment-methods.ts", "src/types/alpha-exchange.ts",
  "packages/contracts/src/index.ts", "packages/contracts/src/trade-terms.ts", "packages/contracts/src/trade-amount.ts",
  "packages/contracts/src/commission-amount.ts", "packages/contracts/src/marketplace-fees.ts",
  "packages/contracts/src/cardless-withdrawal.ts", "packages/contracts/src/price-offer.ts",
] as const;
const CHECKPOINT = { revision: 41, eventHash: "b61492df6398d0e3b1b3b71ea3b61e4d06ab8222189e1702cfb41d73bff3f020",
  stateHash: "5ef934b1da1a1481705e018e34462c8fad3b1169a3bbe5b1af0d70dac4c85872", lastCommandAtMs: 1_793_880_041_000 };
const PREFIX = { revision: 15, eventHash: "71ef75dd8498606f247595324f7d1c807870037fce406f707a01a21f3d502f9f",
  stateHash: "aa48c56140ceb668c1330685f4ffb695edaeb714e2a6dc8c3cd7d58a434d75c8", lastCommandAtMs: 1_793_880_015_000 };
const BACKUP_CHECKSUM = "1f475d6f1c55ac1501ba1f415ff118018f7e4ab77d78c4328efc584f23111ad1";
const RESTORE_AT = 1_793_880_100_000;
const TRON = "tron-sim-usdt", BSC = "bsc-sim-binance-peg-usdt";
const TRON_TRADE = "frozen-v2-tron-trade", BSC_TRADE = "frozen-v2-bsc-trade";
const TRON_LISTING = "frozen-v2-tron-listing", BSC_LISTING = "frozen-v2-bsc-listing";
const WITHDRAWAL = "withdrawal-frozen-v2-held-withdrawal";
const SELLER: Actor = { kind: "seller", id: "frozen-v2-seller" };
const OWNER: Actor = { kind: "operator", id: "frozen-v2-owner" };
const hash = (value: string | Buffer) => createHash("sha256").update(value).digest("hex");
const rowAt = (revision: number) => captured.commands[revision - 1]!;
const replayTo = (revision: number) => verifyVersionedHistory(captured.commands.slice(0, revision));
const checkpoint = (snapshot: ReturnType<typeof replayTo>) => ({ revision: snapshot.revision, eventHash: snapshot.eventHash,
  stateHash: walletDigest(snapshot.state), lastCommandAtMs: snapshot.lastCommandAtMs });

beforeEach(() => {
  vi.stubEnv("NODE_ENV", "test");
  for (const key of ["VERCEL", "VERCEL_ENV", "AWS_LAMBDA_FUNCTION_NAME", "CF_PAGES", "K_SERVICE",
    "ALPHA_WALLET_MAINNET_ENABLED", "ALPHA_WALLET_SIGNING_ENABLED"]) vi.stubEnv(key, undefined);
});
afterEach(() => { vi.unstubAllEnvs(); });

describe("frozen historical wallet v2 compatibility", () => {
  it("pins the original 33-source provenance and fixture bytes, plus the unchanged financial engine and contracts", () => {
    expect(hash(backupText)).toBe("b649ac30737b4ea33523ae04f2db3f476357600d36d966f229d32299fab5d5bb");
    expect(hash(stateText)).toBe("ab9f897ec37291db953ee63eb2161adbc42a4ec086def7db80d927a47e1bfa02");
    expect(hash(provenanceText)).toBe("46cc3cf891507e89c78e6ad7b38be8535f95b29d15f1596afbe255f884069f74");
    expect(provenance).toMatchObject({ sourceCommit: "47f0fc18f33c0f307da53726281db18055a76855",
      sourceTree: "eea3bee815707d3fc62a0d68c69d301bad0ab079", checkoutAtCapture: "6dc63a8997532759727bd8b6691a780d373b6276",
      engineVersion: WALLET_V2_ENGINE_VERSION, backupFormatVersion: 2, checkpoint: CHECKPOINT,
      prefixCheckpoint: PREFIX, backupChecksum: BACKUP_CHECKSUM, facts: { commands: 41, enrollments: 2, acceptanceReceipts: 3 } });
    expect(Object.keys(provenance.sourceSha256)).toHaveLength(33);
    expect(FROZEN_FINANCIAL_SOURCES).toHaveLength(21);
    for (const path of FROZEN_FINANCIAL_SOURCES) {
      expect(provenance.sourceSha256[path], path).toMatch(/^[0-9a-f]{64}$/);
      expect(hash(readFileSync(new URL(`../../../${path}`, import.meta.url))), path).toBe(provenance.sourceSha256[path]);
    }
    expect(inspectVersionedWalletBackup(backupText, { expectedChecksum: BACKUP_CHECKSUM })).toEqual({
      format: "alpha-wallet-simulation-command-backup", formatVersion: 2, mode: "simulation-only", engineVersion: WALLET_V2_ENGINE_VERSION,
      exportedAtMs: 1_793_880_042_000, checkpoint: CHECKPOINT, continuation: captured.continuation,
      checksum: BACKUP_CHECKSUM, commandCount: 41,
    });
  });

  it("retains the exact original v1 prefix and explicit source-bound v2 continuation without moving funds", () => {
    const prefixRows = captured.commands.slice(0, PREFIX.revision);
    const original = verifyDurableHistory(prefixRows);
    expect(original).toMatchObject({ revision: PREFIX.revision, eventHash: PREFIX.eventHash, occurredAtMs: PREFIX.lastCommandAtMs });
    expect(walletDigest(original.state)).toBe(PREFIX.stateHash);
    expect(prefixRows.every(row => parseVersionedCommand(row.command_json).version === 1)).toBe(true);
    const continued = replayTo(16), command = parseV2Command(rowAt(16).command_json);
    expect(command).toEqual(v2Command("continueFromV1", OWNER, "frozen-v2-continuation", { checkpoint: PREFIX }));
    expect(rowAt(16).event_hash).toBe("d2f7d2df062dcf6d230325827e661dda1925d79454c4ff86621092b14323a892");
    expect(continued.state.accounts).toEqual(original.state.accounts);
    expect(continued.state.journal).toEqual(original.state.journal);
    expect(continued.state.trades).toEqual(original.state.trades);
    expect(isV2State(continued.state)).toBe(true);
    if (!isV2State(continued.state)) throw new Error("Frozen continuation must be v2");
    expect(continued.state.continuation).toEqual(captured.continuation);
    expect(continued.state.termsBindings.size).toBe(0);
    expect(continued.state.acceptanceReceipts.size).toBe(0);
    expect(captured.commands.filter(row => row.command_type === "continueFromV1")).toHaveLength(1);
    expect(captured.commands.slice(15).every(row => parseVersionedCommand(row.command_json).version === 2)).toBe(true);
  });

  it("replays every original result, state and event hash into the exact saved tagged state", () => {
    const recovered = verifyVersionedHistory(captured.commands);
    expect(checkpoint(recovered)).toEqual(CHECKPOINT);
    expect(walletJson(recovered.state)).toEqual(capturedState);
    expect(recovered.state.haltReason).toBeNull();
    expect(recovered.state.idempotency.size).toBe(41);
    expect(captured.commands.map(row => Number(row.occurred_at_ms))).toEqual(
      Array.from({ length: 41 }, (_, index) => 1_793_880_001_000 + index * 1_000));
    expect(new Set(captured.commands.map(row => row.command_key)).size).toBe(41);
    if (!isV2State(recovered.state)) throw new Error("Frozen suffix must remain v2");
    assertV2Invariants(recovered.state); assertLedgerInvariants(recovered.state);
    for (const fact of provenance.facts.corrections) {
      expect(recovered.state.acceptanceReceipts.get(fact.receipt.acceptanceKey)).toEqual(fact.receipt);
      expect(rowAt(fact.revision)).toMatchObject({ command_key: fact.commandKey, event_hash: fact.eventHash, result_json: fact.receipt });
    }
  });

  it.each([
    { label: "increase", revision: 18, before: "200000000", after: "300000000", delta: "100000000", fee: "3000000", fiat: "96960" },
    { label: "decrease", revision: 19, before: "300000000", after: "250000000", delta: "-50000000", fee: "2500000", fiat: "80800" },
    { label: "zero", revision: 21, before: "1000050000000000000", after: "1000050000000000000", delta: "0", fee: "10001000000000000", fiat: "323" },
  ])("preserves the recorded $label correction, exact principal journal and separate fee quote", fact => {
    const before = replayTo(fact.revision - 1), after = replayTo(fact.revision);
    const command = parseV2Command(rowAt(fact.revision).command_json);
    if (command.type !== "acceptAmountCorrection") throw new Error("Expected captured correction");
    expect(command.actor).toEqual({ kind: "buyer", id: "frozen-v2-buyer" });
    const tradeId = command.input.walletTradeId, assetId = command.input.acceptedTerms.assetId;
    expect(before.state.trades.get(tradeId)!.amountRaw.toString()).toBe(fact.before);
    expect(after.state.trades.get(tradeId)).toMatchObject({ amountRaw: BigInt(fact.after), buyerFeeRaw: BigInt(fact.fee),
      sellerFeeRaw: BigInt(fact.fee), totalFeeRaw: BigInt(fact.fee) * BigInt(2), fiatTotalMinor: BigInt(fact.fiat), status: "reserved" });
    const receipt = rowAt(fact.revision).result_json as V2AcceptanceReceipt;
    expect(receipt.principalDeltaRaw).toBe(fact.delta);
    expect(receipt.commandKey).toBe(versionedCommandKey(command));
    expect(receipt.commandRevision).toBe(fact.revision);
    expect(receipt.acceptedAtMs).toBe(Number(rowAt(fact.revision).occurred_at_ms));
    const delta = BigInt(fact.delta), journals = after.state.journal.slice(before.state.journal.length);
    if (delta === BigInt(0)) {
      expect(journals).toEqual([]);
      expect(before.state.accounts).toEqual(after.state.accounts);
      expect(receipt.priorTermsDigest).toBe(receipt.acceptedTermsDigest);
    } else {
      expect(journals).toHaveLength(1);
      expect(journals[0].assetId).toBe(assetId);
      expect(journals[0].entries).toEqual(expect.arrayContaining([
        { account: `listing:${command.input.acceptedTerms.walletListingId}`, delta: -delta },
        { account: `trade:${tradeId}`, delta },
      ]));
      expect(journals[0].entries).toHaveLength(2);
    }
    expect(balance(after.state, assetId, `trade:${tradeId}`)).toBe(BigInt(fact.after));
    expect(after.state.commissions).toEqual(before.state.commissions);
    expect(after.state.payouts).toEqual(before.state.payouts);
    expect(expectedCustody(after.state, assetId)).toBe(expectedCustody(before.state, assetId));
  });

  it("retains operator enrollment and the original two-proposal cap across two separate trade bindings", () => {
    for (const revision of [17, 20]) {
      const before = replayTo(revision - 1), after = replayTo(revision), command = parseV2Command(rowAt(revision).command_json);
      expect(command.type).toBe("enrollReservedTrade");
      expect(command.actor).toEqual(OWNER);
      expect(after.state.accounts).toEqual(before.state.accounts);
      expect(after.state.journal).toEqual(before.state.journal);
      expect(after.state.trades).toEqual(before.state.trades);
    }
    const state = replayTo(21).state;
    if (!isV2State(state)) throw new Error("Expected frozen v2 bindings");
    expect(state.termsBindings.size).toBe(2);
    expect(state.termsBindings.get("frozen-v2-request-tron")).toMatchObject({ revision: 2, lastSubmittedAdjustmentCount: 2,
      enrollmentCommandRevision: 17, lastCommandRevision: 19 });
    expect(state.termsBindings.get("frozen-v2-request-bsc")).toMatchObject({ revision: 1, lastSubmittedAdjustmentCount: 1,
      enrollmentCommandRevision: 20, lastCommandRevision: 21 });
    expect(state.acceptanceReceipts.size).toBe(3);
  });

  it("delivers the full resized principal and recognizes fees only through separate commission funding", () => {
    const delivered = replayTo(29).state;
    expect(delivered.trades.get(TRON_TRADE)).toMatchObject({ status: "completed", amountRaw: BigInt("250000000") });
    expect(delivered.payouts.get(`trade-${TRON_TRADE}`)).toMatchObject({ state: "confirmed", amountRaw: BigInt("250000000"), dispatchCount: 1 });
    expect(delivered.commissions.get(TRON_TRADE)).toMatchObject({ amountRaw: BigInt("5000000"), paid: false });
    expect(balance(delivered, TRON, "platform-revenue")).toBe(BigInt(0));
    const state = replayTo(41).state;
    expect(state.commissions.get(TRON_TRADE)).toMatchObject({ amountRaw: BigInt("5000000"), paid: true });
    expect(balance(state, TRON, "platform-revenue")).toBe(BigInt("5000000"));
    expect(balance(state, TRON, `listing:${TRON_LISTING}`)).toBe(BigInt("250000000"));
    expect(balance(state, TRON, "available:frozen-v2-seller")).toBe(BigInt("75000000"));
    expect(balance(state, TRON, `payout:${WITHDRAWAL}`)).toBe(BigInt("25000000"));
    expect(expectedCustody(state, TRON)).toBe(BigInt("355000000"));
    expect(state.trades.get(BSC_TRADE)).toMatchObject({ status: "completed", amountRaw: BigInt("1000050000000000000"),
      buyerFeeRaw: BigInt("10001000000000000"), sellerFeeRaw: BigInt("10001000000000000"), fiatTotalMinor: BigInt("323") });
    expect(state.payouts.get(`trade-${BSC_TRADE}`)).toMatchObject({ state: "confirmed", amountRaw: BigInt("1000050000000000000"), dispatchCount: 1 });
    expect(balance(state, BSC, `listing:${BSC_LISTING}`)).toBe(BigInt("8999950000000000000"));
    expect(balance(state, BSC, "platform-revenue")).toBe(BigInt("20002000000000000"));
    expect(expectedCustody(state, BSC)).toBe(BigInt("9019952000000000000"));
    expect([...state.commissions.values()].every(commission => commission.paid)).toBe(true);
    expect(state.payouts.get(WITHDRAWAL)).toMatchObject({ state: "submission_unknown", dispatchCount: 1,
      providerReference: "sim-payout-withdrawal-frozen-v2-held-withdrawal" });
    assertLedgerInvariants(state);
  });

  it.each([SELLER, OWNER])("does not reinterpret $kind authority as the buyer of an inherited reserveTrade", actor => {
    const snapshot = replayTo(41), before = walletDigest(snapshot.state);
    const command = v2Command("reserveTrade", actor, `future-${actor.kind}-reserve`, {
      id: "future-seller-trade", listingId: TRON_LISTING, amount: "1", destination: "sim://tron-sim-usdt/recipient/frozen-v2-buyer",
    });
    expect(() => applyV2Command(snapshot.state, command, { ...checkpoint(snapshot), at: RESTORE_AT })).toThrow("Requires buyer authority");
    expect(walletDigest(snapshot.state)).toBe(before);
  });

  it.each([
    { version: 2, engineVersion: WALLET_V2_ENGINE_VERSION, type: "acceptInitialTrade" },
    { version: 2, engineVersion: WALLET_V2_ENGINE_VERSION, type: "acceptInitialRequest" },
    { version: 3, engineVersion: "alpha-wallet-simulation-v3", type: "acceptInitialTrade" },
    { version: 2, engineVersion: "alpha-wallet-simulation-v3", type: "reserveTrade" },
  ])("rejects unimplemented seller command $type under version $version / $engineVersion", envelope => {
    expect(() => parseVersionedCommand({ ...envelope, actor: SELLER, requestId: "future-seller-acceptance", input: {} })).toThrow();
  });

  it("refuses a reattributed historical buyer reservation even when its outer identity hash is recomputed", () => {
    const rows = structuredClone(captured.commands), row = rows[4];
    const original = parseVersionedCommand(row.command_json);
    const forged = { ...original, actor: SELLER };
    row.command_json = forged; row.command_key = versionedCommandKey(forged); row.input_hash = walletDigest(forged);
    expect(() => verifyVersionedHistory(rows)).toThrow(/committed command no longer replays/);
  });

  it("refuses a future seller command spliced into otherwise recorded v2 history", () => {
    const rows = structuredClone(captured.commands), row = rows[17];
    row.command_json = { version: 3, engineVersion: "alpha-wallet-simulation-v3", type: "acceptInitialTrade",
      actor: SELLER, requestId: "future-seller-acceptance", input: {} };
    row.command_type = "acceptInitialTrade"; row.input_hash = walletDigest(row.command_json);
    expect(() => verifyVersionedHistory(rows)).toThrow(/Unknown or malformed durable command version/);
  });

  it("restores and reopens exact recorded rows, recovers original receipts and never reissues historical payout dispatch", async () => {
    const directory = await mkdtemp(join(tmpdir(), "alpha-wallet-frozen-v2-"));
    const dataDir = join(directory, "restored");
    let store: WalletStore | undefined;
    try {
      store = await createFileWalletStore({ mode: "simulation-only", dataDir });
      const restored = await restoreVersionedWalletBackup({ mode: "simulation-only", store, backup: backupText,
        acknowledgeFreshTarget: true, expectedChecksum: BACKUP_CHECKSUM, clock: () => RESTORE_AT });
      expect(restored.backup.checkpoint).toEqual(CHECKPOINT);
      expect(restored).toMatchObject({ quarantined: true, restored: { revision: 42, lastCommandAtMs: RESTORE_AT } });
      await store.close(); store = undefined;
      store = await createFileWalletStore({ mode: "simulation-only", dataDir });
      const wallet = createVersionedDurableWallet({ mode: "simulation-only", store, clock: () => RESTORE_AT });
      const rows = await store.transaction(async tx => (await tx.query(`SELECT revision,command_key,command_type,
        occurred_at_ms::text AS occurred_at_ms,command_json,input_hash,result_json,result_hash,state_hash,previous_event_hash,event_hash
        FROM alpha_wallet_simulation.commands ORDER BY revision`)).rows);
      expect(rows.slice(0, 41)).toEqual(captured.commands);
      expect(rows).toHaveLength(42);
      expect(rows[41]).toMatchObject({ command_type: "pause", command_key: restored.quarantineCommandKey,
        occurred_at_ms: String(RESTORE_AT), previous_event_hash: CHECKPOINT.eventHash });
      const before = await wallet.snapshot();
      expect(before.state.haltReason).toBe("Operator emergency pause");
      expect(checkpoint(before)).toEqual(restored.restored);
      expect(before.state.idempotency.size).toBe(42);
      expect(walletJson({ ...before.state, haltReason: null,
        idempotency: new Map([...before.state.idempotency].slice(0, 41)) })).toEqual(capturedState);
      let dispatches = 0;
      for (const row of captured.commands) {
        const command = parseVersionedCommand(row.command_json);
        const duplicate = await wallet.execute(command);
        expect(duplicate).toMatchObject({ replayed: true, revision: row.revision, commandKey: row.command_key, eventHash: row.event_hash });
        if (command.type === "beginDispatch") {
          dispatches++;
          expect(row.result_json).toMatchObject({ shouldDispatch: true });
          expect(duplicate.result).toEqual({ shouldDispatch: false, payout: before.state.payouts.get(command.input) });
        } else {
          expect(walletJson(duplicate.result)).toEqual(row.result_json);
          expect(walletDigest(duplicate.result)).toBe(row.result_hash);
        }
        if (command.version === 2 && command.type === "acceptAmountCorrection") {
          const retried = await wallet.execute({ ...command, requestId: `retry-${row.revision}` });
          expect(retried).toEqual(duplicate);
        }
      }
      expect(dispatches).toBe(3);
      const originalReserve = parseVersionedCommand(rowAt(5).command_json);
      if (originalReserve.type !== "reserveTrade") throw new Error("Expected the original buyer reservation");
      await expect(wallet.execute(v2Command("reserveTrade", originalReserve.actor, originalReserve.requestId, originalReserve.input)))
        .rejects.toThrow(/different payload or engine version/);
      const provider = {
        kind: "alpha-wallet-file-fake-provider" as const,
        lookup: vi.fn(async () => ({ status: "not_found" as const })),
        submit: vi.fn(async () => { throw new Error("Frozen v2 recovery must not submit a replacement"); }),
        finalize: vi.fn(async () => { throw new Error("No provider finalization belongs to historical recovery"); }),
      } satisfies FileFakeProvider;
      const worker = createVersionedSimulationPayoutWorker({ mode: "simulation-only", wallet, provider });
      expect(await worker.step(WITHDRAWAL)).toEqual({ payoutId: WITHDRAWAL, status: "provider_lookup_required" });
      expect(await worker.step(`trade-${TRON_TRADE}`)).toEqual({ payoutId: `trade-${TRON_TRADE}`, status: "confirmed" });
      expect(provider.lookup).toHaveBeenCalledExactlyOnceWith(before.state.payouts.get(WITHDRAWAL));
      expect(provider.submit).not.toHaveBeenCalled(); expect(provider.finalize).not.toHaveBeenCalled();
      await expect(wallet.execute(v2Command("beginDispatch", { kind: "dispatcher", id: "frozen-v2-dispatcher" },
        "replacement-after-frozen-restore", WITHDRAWAL))).rejects.toThrow(/Wallet paused/);
      await expect(wallet.execute(v2Command("reserveTrade", SELLER, "seller-after-frozen-restore", {
        id: "future-seller-trade", listingId: TRON_LISTING, amount: "1", destination: "sim://tron-sim-usdt/recipient/frozen-v2-buyer",
      }))).rejects.toThrow("Requires buyer authority");
      expect(await wallet.snapshot()).toEqual(before);
      assertLedgerInvariants(before.state);
    } finally {
      try { await store?.close(); }
      finally { await rm(directory, { recursive: true, force: true }); }
    }
  }, 120_000);
});
